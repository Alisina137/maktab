export function adminText(locale: AdminLocale, english: string): string {
  if (locale === "en") return english;
  return (locale === "fa-AF" ? fa : ps)[english] ?? english;
}

export function adminDirection(locale: AdminLocale): "rtl" | "ltr" {
  return locale === "en" ? "ltr" : "rtl";
}

export function readAdminLocale(): AdminLocale {
  if (typeof window === "undefined") return ADMIN_DEFAULT_LOCALE;
  const value = window.localStorage.getItem(ADMIN_LOCALE_STORAGE_KEY);
  return value === "fa-AF" || value === "ps-AF" || value === "en" ? value : ADMIN_DEFAULT_LOCALE;
}

export function saveAdminLocale(locale: AdminLocale) {
  if (typeof window !== "undefined") {
    window.localStorage.setItem(ADMIN_LOCALE_STORAGE_KEY, locale);
  }
}


export function adminFormat(
  locale: AdminLocale,
  englishTemplate: string,
  values: Record<string, string | number>
): string {
  let result = adminText(locale, englishTemplate);
  for (const [key, value] of Object.entries(values)) {
    result = result.replaceAll(`{${key}}`, String(value));
  }
  return result;
}

export function adminErrorText(locale: AdminLocale, cause: unknown, fallback: string): string {
  const fallbackText = adminText(locale, fallback);
  if (!(cause instanceof Error)) return fallbackText;
  if (locale === "en") return cause.message || fallback;

  const translated = adminText(locale, cause.message);
  return translated !== cause.message ? translated : fallbackText;
}
